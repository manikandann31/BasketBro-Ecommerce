import { useMemo } from "react";
import { Link, useLocation, useParams } from "react-router-dom";

function OrderConfirmation() {
    const { orderId } = useParams();
    const location = useLocation();
    const order = useMemo(() => {
        if (location.state?.order?.orderId === orderId) return location.state.order;
        try {
            return (JSON.parse(localStorage.getItem("basketbroOrders") || "[]"))
                .find((item) => item.orderId === orderId) || null;
        } catch { return null; }
    }, [location.state, orderId]);

    const money = (value) => Number(value).toLocaleString("en-IN", {
        style: "currency", currency: "INR", maximumFractionDigits: 2
    });

    const downloadReceipt = () => {
        if (!order) return;
        const safe = (value) => String(value ?? "").replace(/[&<>"']/g, (char) => ({
            "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;"
        })[char]);
        const rows = order.items.map((item) => `
            <tr><td>${safe(item.name)}</td><td>${item.quantity}</td>
            <td>${money(item.price)}</td><td>${money(item.subtotal)}</td></tr>`).join("");
        const html = `<!doctype html><html><head><meta charset="utf-8"><title>BasketBro Receipt ${safe(order.orderId)}</title>
        <style>body{font:15px Arial,sans-serif;color:#172033;max-width:850px;margin:40px auto;padding:24px}h1{color:#2563eb}table{width:100%;border-collapse:collapse;margin:24px 0}th,td{padding:12px;border:1px solid #dbe2ea;text-align:left}th{background:#eff6ff}.total{text-align:right;font-size:20px;font-weight:bold}.muted{color:#64748b}.grid{display:grid;grid-template-columns:1fr 1fr;gap:20px}</style></head><body>
        <h1>BasketBro</h1><h2>Order Receipt</h2><p><b>Order ID:</b> ${safe(order.orderId)}<br><b>Order Date:</b> ${safe(new Date(order.createdAt).toLocaleString("en-IN"))}</p>
        <div class="grid"><section><h3>Customer details</h3><p>${safe(order.customer.customerName)}<br>${safe(order.customer.email)}<br>${safe(order.customer.phone)}</p></section>
        <section><h3>Delivery address</h3><p>${safe(order.customer.address)}<br>${safe(order.customer.city)}, ${safe(order.customer.state)} - ${safe(order.customer.postalCode)}</p></section></div>
        <table><thead><tr><th>Product</th><th>Quantity</th><th>Unit price</th><th>Subtotal</th></tr></thead><tbody>${rows}</tbody></table>
        <p><b>Payment method:</b> ${safe(order.paymentMethod)}<br><b>Payment status:</b> ${safe(order.paymentStatus)}<br><b>Order status:</b> ${safe(order.orderStatus)}</p>
        <p class="total">Grand Total: ${money(order.total)}</p><p class="muted">Demo receipt generated by BasketBro. This is not a tax invoice or proof of real payment.</p></body></html>`;
        const blob = new Blob([html], { type: "text/html;charset=utf-8" });
        const url = URL.createObjectURL(blob);
        const anchor = document.createElement("a");
        anchor.href = url;
        anchor.download = `BasketBro-Receipt-${order.orderId}.html`;
        document.body.appendChild(anchor);
        anchor.click();
        anchor.remove();
        URL.revokeObjectURL(url);
    };

    if (!order) return (
        <div className="container order-confirmation-page">
            <h1>Order details unavailable</h1>
            <p>This order may not exist in this browser session.</p>
            <Link to="/">Continue Shopping</Link>
        </div>
    );

    return (
        <div className="container order-confirmation-page">
            <div className="order-success-icon" aria-hidden="true">✓</div>
            <p className="checkout-step-label">BASKETBRO ORDER CONFIRMED</p>
            <h1>Thank you for your order!</h1>
            <p>Your demo order has been created successfully.</p>
            <div className="order-receipt-card">
                <div className="order-receipt-heading"><div><span>Order ID</span><strong>{order.orderId}</strong></div><span className="order-status-badge">{order.orderStatus}</span></div>
                <p className="order-date">{new Date(order.createdAt).toLocaleString("en-IN")}</p>
                <h2>Products</h2>
                <div className="order-product-list">
                    {order.items.map((item) => (
                        <div className="order-product-row" key={item.productId}>
                            <div><strong>{item.name}</strong><span>Quantity: {item.quantity} × {money(item.price)}</span></div>
                            <strong>{money(item.subtotal)}</strong>
                        </div>
                    ))}
                </div>
                <div className="order-total-row"><span>Total paid / payable</span><strong>{money(order.total)}</strong></div>
                <h2>Customer details</h2>
                <p><strong>{order.customer.customerName}</strong><br />{order.customer.email}<br />{order.customer.phone}</p>
                <h2>Delivery address</h2>
                <p>{order.customer.address}, {order.customer.city}, {order.customer.state} - {order.customer.postalCode}</p>
                <p><strong>Payment:</strong> {order.paymentMethod} · {order.paymentStatus}</p>
                <button type="button" className="receipt-download-button" onClick={downloadReceipt}>⬇ Download Order Receipt</button>
            </div>
            <Link className="continue-shopping-link" to="/">Continue Shopping</Link>
        </div>
    );
}
export default OrderConfirmation;